import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { build } from "esbuild";
import { homedir } from "node:os";
import { join } from "node:path";

const plugins = [
  {
    name: "BitchTracker",
    description:
      "Shadow-CLJS BetterDiscord plugin for OpenPlanner Discord ingestion, reaction labeling, and review backfill.",
    contract: "module.exports = meta => ({ start, stop, getSettingsPanel, runBackfill, flush })",
  },
  {
    name: "KnoxxLens",
    description:
      "Ask a Knoxx agent about the open Discord channel, with explicit context chips. Talks to Knoxx through the bitch-tracker bot.",
    contract: "module.exports = meta => ({ start, stop, getSettingsPanel })",
  },
];

const outDir = new URL("../dist/", import.meta.url);
const bdCandidates = [
  join(homedir(), ".config", "BetterDiscord", "plugins"),
  join(homedir(), "snap", "discord", "current", ".config", "BetterDiscord", "plugins"),
];

async function copyToBetterDiscord(outPath, fileName) {
  if (process.env.BETTERDISCORD_COPY === "0") {
    console.log(`BETTERDISCORD_COPY=0; not installing ${fileName}`);
    return;
  }
  for (const dir of bdCandidates) {
    try {
      const target = join(dir, fileName);
      await copyFile(outPath, target);
      console.log(`copied to ${target}`);
      return;
    } catch (err) {
      if (err.code !== "ENOENT") {
        console.warn(`failed to copy to ${dir}: ${err.message}`);
        return;
      }
    }
  }
  console.warn("BetterDiscord plugins directory not found; skipped copy");
}

async function writePlugin({ name, description, contract }) {
  const rawPath = new URL(`../build/${name}.raw.js`, import.meta.url);
  const outPath = new URL(`../dist/${name}.plugin.js`, import.meta.url);
  const header = `/**
 * @name ${name}
 * @author open-hax
 * @description ${description}
 * @version 0.0.1
 */`;

  const raw = await readFile(rawPath, "utf8");
  const js = raw.replace(/^#!.*\n/, "");

  const bundled = await build({
    stdin: {
      contents: js,
      resolveDir: new URL("../", import.meta.url).pathname,
      sourcefile: `${name}.raw.js`,
      loader: "js",
    },
    bundle: true,
    platform: "browser",
    format: "cjs",
    write: false,
  });

  if (!bundled.outputFiles?.[0]?.text) {
    throw new Error(`esbuild produced no output for ${name}`);
  }

  const body = `${header}\n\n// Generated by shadow-cljs and bundled with esbuild.\n// The CLJS entrypoint preserves the BetterDiscord rule:\n// ${contract}\n${bundled.outputFiles[0].text}`;

  await writeFile(outPath, body);
  console.log(`wrote ${outPath.pathname}`);
  await copyToBetterDiscord(outPath.pathname, `${name}.plugin.js`);
}

await mkdir(outDir, { recursive: true });
for (const plugin of plugins) {
  await writePlugin(plugin);
}
